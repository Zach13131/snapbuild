export type PilotContour = (typeof pilotContours)[number]["id"];
export type PilotPack = (typeof pilotPacks)[number]["id"];
export type PilotTeam = (typeof pilotTeams)[number]["id"];

export function composePilotMessage(scope: {
  contour: PilotContour;
  pack: PilotPack;
  team: PilotTeam;
  plan?: string;
}) {
  const contour = pilotContours.find((item) => item.id === scope.contour)?.label ?? scope.contour;
  const pack = pilotPacks.find((item) => item.id === scope.pack)?.label ?? scope.pack;
  const team = pilotTeams.find((item) => item.id === scope.team)?.label ?? scope.team;
  const plan =
    scope.plan === "start" ? "Старт" : scope.plan === "team" ? "Команда" : scope.plan === "contour" ? "Контур" : "";
  return [
    contour,
    pack,
    team,
    plan ? `тариф ${plan}` : "",
  ]
    .filter(Boolean)
    .join(" · ");
}

export function asset(path: string) {
  const base = import.meta.env.BASE_URL ?? "./";
  return `${base}${path.replace(/^\//, "")}`;
}
